"""Short vertical (9:16) original: a ball that grows on every bounce until it fills the circle.
100% generated by code: visuals (pycairo) + music/sfx (numpy synth). No third-party assets.
Usage: python3 make_video.py [out.mp4]
"""
import math, subprocess, sys, wave, os, random
import numpy as np
import cairo

W, H, FPS = 1080, 1920, 60
CX, CY, R = W / 2, 1010, 430          # arena
G = 2600.0                             # gravity px/s^2
GROW = 1.3                             # px added to ball radius per bounce
R0 = 16.0
SUB = 16                               # physics substeps per frame
OUTRO = 3.2                            # seconds after the ball fills the circle
SR = 44100
random.seed(7)

def hsv(h, s=0.85, v=1.0):
    h = h % 1.0; i = int(h * 6); f = h * 6 - i
    p, q, t = v*(1-s), v*(1-s*f), v*(1-s*(1-f))
    return [(v,t,p),(q,v,p),(p,v,t),(p,q,v),(t,p,v),(v,p,q)][i % 6]

# ---------------- simulate ----------------
def simulate():
    x, y = CX + 60, CY - 250
    vx, vy = 520.0, 0.0
    r = R0
    dt = 1.0 / (FPS * SUB)
    frames, bounces = [], []           # bounces: (time, count, radius)
    t, n, done_t = 0.0, 0, None
    f = 0
    while True:
        for _ in range(SUB):
            if done_t is None:
                vy += G * dt
                x += vx * dt; y += vy * dt
                dx, dy = x - CX, y - CY
                d = math.hypot(dx, dy)
                if d + r > R:
                    nx, ny = dx / d, dy / d
                    vn = vx * nx + vy * ny
                    if vn > 0:
                        vx -= 2 * vn * nx; vy -= 2 * vn * ny
                        # keep it lively: small tangential kick, minimum speed
                        sp = math.hypot(vx, vy)
                        target = max(sp, 1500.0)
                        vx, vy = vx / sp * target, vy / sp * target
                        vx += -ny * 40; vy += nx * 40
                        n += 1
                        r = min(R - 3, r + GROW)
                        bounces.append((t, n, r))
                        if r >= R - 3:
                            done_t = t
                    x, y = CX + nx * (R - r), CY + ny * (R - r)
            t += dt
        frames.append((x, y, r, n))
        f += 1
        if done_t is not None and t > done_t + OUTRO:
            break
        if t > 70:
            raise SystemExit("simulation too long; tune GROW")
    return frames, bounces, done_t

frames, bounces, done_t = simulate()
print(f"frames={len(frames)} duration={len(frames)/FPS:.1f}s bounces={len(bounces)} fill_at={done_t:.1f}s")

# ---------------- audio ----------------
def synth(total):
    N = int(total * SR) + SR
    out = np.zeros(N, np.float32)
    # A-minor pentatonic run that climbs as the ball grows
    scale = [0, 3, 5, 7, 10]
    melody = [0, 2, 4, 2, 3, 1, 4, 3, 0, 2, 4, 5, 3, 4, 2, 1]
    last = -1.0
    for (tb, n, r) in bounces:
        if tb - last < 0.045:  # avoid machine-gun at the end
            continue
        last = tb
        step = melody[n % len(melody)] + int((r - R0) / (R - R0) * 10)
        semi = scale[step % 5] + 12 * (step // 5)
        freq = 220.0 * 2 ** (semi / 12)
        dur = 0.55
        tt = np.arange(int(dur * SR)) / SR
        env = np.exp(-tt * 7) * np.minimum(1, tt * 400)
        tone = (np.sin(2*np.pi*freq*tt) + 0.35*np.sin(2*np.pi*2*freq*tt) + 0.12*np.sin(2*np.pi*3*freq*tt)) * env
        click = np.exp(-tt * 90) * np.sin(2*np.pi*90*tt) * 0.6
        s = int(tb * SR)
        seg = (tone * 0.28 + click * 0.25).astype(np.float32)
        out[s:s+len(seg)] += seg[:N - s]
    # soft pad that rises in intensity
    tt = np.arange(N) / SR
    prog = np.clip(tt / max(done_t, 1), 0, 1)
    pad = sum(np.sin(2*np.pi*f*tt + k) for k, f in enumerate([110, 164.81, 220, 261.63]))
    out += (pad * 0.025 * (0.4 + 0.6*prog) * (tt < done_t)).astype(np.float32)
    # riser into the finale
    rise = (tt > done_t - 3) & (tt < done_t)
    nz = np.random.default_rng(1).standard_normal(N).astype(np.float32)
    out += nz * 0.05 * rise * np.clip((tt - (done_t - 3)) / 3, 0, 1)**2
    # finale: boom + major chord
    s = int(done_t * SR)
    td = np.arange(int(3.0 * SR)) / SR
    boom = np.sin(2*np.pi*(55 + 80*np.exp(-td*20))*td) * np.exp(-td*3.5) * 0.9
    chord = sum(np.sin(2*np.pi*f*td) for f in [440, 554.37, 659.25, 880]) * np.exp(-td*1.2) * 0.12
    burst = nz[:len(td)] * np.exp(-td*12) * 0.25
    fin = (boom + chord + burst).astype(np.float32)
    out[s:s+len(fin)] += fin[:N - s]
    out = out[:int(total * SR)]
    out /= max(1e-6, np.abs(out).max()) / 0.9
    return out

# ---------------- drawing ----------------
FONT = "Inter"
def text(ctx, s, x, y, size, rgba=(1,1,1,1), weight=cairo.FONT_WEIGHT_BOLD, center=True, stroke=0):
    ctx.select_font_face(FONT, cairo.FONT_SLANT_NORMAL, weight)
    ctx.set_font_size(size)
    ext = ctx.text_extents(s)
    px = x - (ext.width/2 + ext.x_bearing) if center else x
    ctx.move_to(px, y)
    ctx.text_path(s)
    if stroke:
        ctx.set_source_rgba(0, 0, 0, rgba[3]); ctx.set_line_width(stroke)
        ctx.set_line_join(cairo.LINE_JOIN_ROUND)
        ctx.stroke_preserve()
    ctx.set_source_rgba(*rgba); ctx.fill()

def ease_out(x): x = min(max(x, 0), 1); return 1 - (1 - x) ** 3

particles = []
def spawn_burst(x, y, k, hue):
    for _ in range(k):
        a = random.random() * 2 * math.pi; sp = random.uniform(300, 1600)
        particles.append([x, y, math.cos(a)*sp, math.sin(a)*sp, random.uniform(0.6, 1.6), hue + random.uniform(-.1,.1), random.uniform(4, 12)])

def render(out_path):
    total = len(frames) / FPS
    audio = synth(total)
    wav = out_path + ".wav"
    with wave.open(wav, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((audio * 32767).astype(np.int16).tobytes())

    ff = subprocess.Popen([
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "rawvideo", "-pix_fmt", "bgra", "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-",
        "-i", wav,
        "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p",
        "-profile:v", "high", "-movflags", "+faststart",
        "-c:a", "aac", "-b:a", "192k", "-shortest", out_path], stdin=subprocess.PIPE)

    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H)
    ctx = cairo.Context(surf)
    trail = []
    flash = 0.0
    bi = 0
    finished = False
    shake = 0.0
    for fi, (x, y, r, n) in enumerate(frames):
        t = fi / FPS
        prog = (r - R0) / (R - 3 - R0)
        hue = 0.55 + prog * 1.2
        # new bounces this frame -> ring flash
        while bi < len(bounces) and bounces[bi][0] <= t:
            flash = 1.0; bi += 1
        if done_t is not None and t >= done_t and not finished:
            finished = True; shake = 1.0
            spawn_burst(CX, CY, 420, hue)

        # background
        bg = cairo.RadialGradient(CX, CY, 50, CX, CY, 1300)
        c = hsv(hue, 0.7, 0.16 + 0.10 * flash)
        bg.add_color_stop_rgb(0, *c); bg.add_color_stop_rgb(1, 0.02, 0.02, 0.04)
        ctx.set_source(bg); ctx.paint()

        ctx.save()
        if shake > 0:
            ctx.translate(random.uniform(-1,1)*30*shake, random.uniform(-1,1)*30*shake)

        # rainbow trail (ghost copies)
        if not finished:
            trail.append((x, y, r, hue))
            trail = trail[-26:]
        for i, (tx, ty, tr, th) in enumerate(trail):
            a = (i + 1) / len(trail)
            ctx.set_source_rgba(*hsv(th + (1 - a) * 0.25), 0.10 * a)
            ctx.arc(tx, ty, tr * (0.6 + 0.4*a), 0, 2*math.pi); ctx.fill()

        # arena ring + glow
        rc = hsv(hue + 0.5, 0.6, 1)
        for wdt, al in [(40, 0.05 + 0.10*flash), (20, 0.10 + 0.2*flash), (8, 0.9)]:
            ctx.set_source_rgba(*rc, al); ctx.set_line_width(wdt)
            ctx.arc(CX, CY, R + 4, 0, 2*math.pi); ctx.stroke()

        # ball
        if not finished:
            col = hsv(hue)
            glow = cairo.RadialGradient(x, y, r * 0.5, x, y, r * 1.8)
            glow.add_color_stop_rgba(0, *col, 0.45); glow.add_color_stop_rgba(1, *col, 0)
            ctx.set_source(glow); ctx.arc(x, y, r*1.8, 0, 2*math.pi); ctx.fill()
            body = cairo.RadialGradient(x - r*0.35, y - r*0.35, r*0.1, x, y, r)
            body.add_color_stop_rgb(0, *[min(1, v + 0.45) for v in col])
            body.add_color_stop_rgb(1, *[v * 0.75 for v in col])
            ctx.set_source(body); ctx.arc(x, y, r, 0, 2*math.pi); ctx.fill()
        else:
            # filled circle pulses
            k = ease_out((t - done_t) / 0.5)
            col = hsv(hue)
            ctx.set_source_rgba(*col, 1 - 0.6*k); ctx.arc(CX, CY, R - 3, 0, 2*math.pi); ctx.fill()
            # shockwave ring
            sw = R + k * 900
            ctx.set_source_rgba(1, 1, 1, max(0, 1 - k)); ctx.set_line_width(30 * (1 - k) + 2)
            ctx.arc(CX, CY, sw, 0, 2*math.pi); ctx.stroke()

        # particles
        for p in particles:
            p[0] += p[2]/FPS; p[1] += p[3]/FPS; p[3] += 900/FPS; p[2] *= 0.985; p[4] -= 1/FPS
            if p[4] > 0:
                ctx.set_source_rgba(*hsv(p[5]), min(1, p[4])); ctx.arc(p[0], p[1], p[6], 0, 2*math.pi); ctx.fill()
        particles[:] = [p for p in particles if p[4] > 0]
        ctx.restore()

        # --- UI text ---
        pop = ease_out(t / 0.35)
        if not finished:
            text(ctx, "CADA REBOTE", W/2, 250, 92 * (0.6 + 0.4*pop), stroke=10)
            text(ctx, "LA HACE MÁS GRANDE", W/2, 360, 80 * (0.6 + 0.4*pop), rgba=(*hsv(hue, 0.6), 1), stroke=10)
            text(ctx, "¿Llenará el círculo? 👀".replace(" 👀", ""), W/2, 455, 54, rgba=(1,1,1,0.85), weight=cairo.FONT_WEIGHT_NORMAL)
        else:
            k = ease_out((t - done_t) / 0.4)
            text(ctx, "¡LO LOGRÓ!", W/2, 330, 150 * (0.5 + 0.5*k), rgba=(1,1,1,1), stroke=14)
            if t - done_t > 0.9:
                k2 = ease_out((t - done_t - 0.9) / 0.4)
                text(ctx, "¿Adivinaste cuántos rebotes?", W/2, 1760, 56, rgba=(1,1,1,k2))
                text(ctx, "Escríbelo en comentarios ↓", W/2, 1840, 50, rgba=(*hsv(hue,0.5),k2), weight=cairo.FONT_WEIGHT_NORMAL)

        # counter + progress bar
        cy0 = 1600
        sc = 1 + 0.18 * flash
        text(ctx, f"{n}", W/2, cy0, 120 * sc, rgba=(1,1,1,1), stroke=8)
        text(ctx, "REBOTES", W/2, cy0 + 55, 40, rgba=(1,1,1,0.7), weight=cairo.FONT_WEIGHT_NORMAL)
        if not finished:
            bx, bw = 190, W - 380
            ctx.set_source_rgba(1,1,1,0.15); ctx.rectangle(bx, 1745, bw, 16); ctx.fill()
            ctx.set_source_rgba(*hsv(hue), 1); ctx.rectangle(bx, 1745, bw * min(1, prog), 16); ctx.fill()
            text(ctx, f"{int(min(1,prog)*100)}% lleno", W/2, 1815, 40, rgba=(1,1,1,0.75), weight=cairo.FONT_WEIGHT_NORMAL)

        flash *= 0.82; shake *= 0.9
        surf.flush()
        ff.stdin.write(surf.get_data())
        if fi % 300 == 0:
            print(f"  frame {fi}/{len(frames)}", flush=True)
    ff.stdin.close(); ff.wait()
    os.remove(wav)
    print("saved", out_path)

if __name__ == "__main__":
    render(sys.argv[1] if len(sys.argv) > 1 else "video_viral.mp4")
